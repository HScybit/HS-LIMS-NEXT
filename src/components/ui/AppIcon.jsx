export default function AppIcon({
  name,
  size,
  stroke = 1.8,
  className = '',
  style,
  ...props
}) {
  const IconComponent = iconComponentMap[normalizeIconName(name)];

  if (!IconComponent) {
    return null;
  }

  const resolvedSize = size ?? '1em';
  const explicitSizeStyle = size == null
    ? null
    : {
        width: resolvedSize,
        height: resolvedSize,
        fontSize: resolvedSize,
      };

  return (
    <IconComponent
      className={cx('smplfy-icon', className)}
      size={resolvedSize}
      stroke={stroke}
      style={{
        lineHeight: 1,
        display: 'inline-flex',
        alignItems: 'center',
        justifyContent: 'center',
        flexShrink: 0,
        ...explicitSizeStyle,
        ...style,
      }}
      aria-hidden="true"
      {...props}
    />
  );
}
