import { HttpError } from '../auth/errors.js';
import { bool, fieldsOnly, integer, text, uuid } from '../templates/input.js';
import { customFieldTypes, customFieldAssociations, customFieldLegacyAssociations, customFieldDateFormats,
  customFieldDateTimeFormats, customFieldGenerationTimes } from './custom-field-config.js';

const textFields = {
  label: ['Label', 200], key: ['Key', 150], description: ['Description', 16000], autoGenerated: ['Source', 250],
  scheme: ['Scheme', 5000], nablDisplayTerm: ['NABL Term', 250], nonNablDisplayTerm: ['NON-NABL Term', 250],
  splitter: ['Splitter Character', 20], filterSearchType: ['Filter Search Type', 40],
};
const booleanFields = ['showInList', 'showInFilter', 'allowsMultiple', 'isRequired', 'associateRoleSpecificUsers',
  'showInDashboard', 'showInReport', 'validateUniqueness', 'hideFromSampleCreation'];

function cleanText(value, label, maximum, optional = true) {
  const result = text(value, label, maximum, { optional }).trim();
  if (result.includes('\0')) throw new HttpError(400, 'invalid_input', `${label} cannot contain null characters.`);
  return result;
}

function choice(value, options, label) {
  if (!options.some((option) => option.value === value)) throw new HttpError(400, 'invalid_custom_field', `${label} is invalid.`);
  return value;
}

function boundedNumber(value, label, fallback, maximum) {
  if (value === undefined || value === null || value === '') return fallback;
  if (!['string', 'number'].includes(typeof value) || (typeof value === 'string' && !value.trim())) throw new HttpError(400, 'invalid_input', `${label} must be a finite number.`);
  const result = Number(value);
  if (!Number.isFinite(result) || result < 0 || result > maximum) throw new HttpError(400, 'invalid_input', `${label} must be between 0 and ${maximum}.`);
  return result === 0 ? 0 : result;
}

export function customFieldInput(input) {
  fieldsOnly(input, ['id', 'requestId', 'revision', ...Object.keys(textFields), ...booleanFields, 'fieldType', 'associatedWith',
    'paddedNumber', 'displayOrder', 'dateFormat', 'datetimeFormat', 'generatedAt', 'associatedWithRoleId', 'roleIdsCanEdit', 'options']);
  const result = { id: uuid(input.id, 'Custom field').toLowerCase(), requestId: uuid(input.requestId, 'Save request').toLowerCase(),
    revision: integer(input.revision, 'Revision', 0, 2_147_483_646) };
  for (const [field, [label, maximum]] of Object.entries(textFields)) result[field] = cleanText(input[field], label, maximum, !['label', 'key'].includes(field));
  result.key = result.key.toLowerCase();
  if (!/^[a-z0-9_]+$/.test(result.key)) throw new HttpError(400, 'invalid_custom_field_key', 'Key can only contain letters, numbers, and underscores. Spaces are not allowed.');
  result.splitter ||= '/';
  for (const field of booleanFields) result[field] = bool(input[field] === undefined ? false : input[field], field);
  result.fieldType = choice(input.fieldType === undefined || input.fieldType === '' ? 'text' : input.fieldType, customFieldTypes, 'Data Type');
  result.associatedWith = choice(input.associatedWith, [...customFieldAssociations, ...customFieldLegacyAssociations], 'Associated With');
  result.generatedAt = choice(input.generatedAt === undefined || input.generatedAt === '' ? 'on_init' : input.generatedAt, customFieldGenerationTimes, 'Generated At');
  result.paddedNumber = boundedNumber(input.paddedNumber, 'Padded Number', 0, 1000);
  result.displayOrder = boundedNumber(input.displayOrder, 'Order Index', 10000, 100000);
  const dateFormat = cleanText(input.dateFormat, 'Date Format', 80);
  const datetimeFormat = cleanText(input.datetimeFormat, 'Date-Time Format', 80);
  result.dateFormat = result.fieldType === 'date' ? (customFieldDateFormats.some((format) => format.value === dateFormat) ? dateFormat : 'DD/MM/YYYY') : '';
  result.datetimeFormat = result.fieldType === 'date_time' ? (customFieldDateTimeFormats.some((format) => format.value === datetimeFormat) ? datetimeFormat : 'DD/MM/YYYY HH:mm:ss') : '';
  result.associatedWithRoleId = input.associatedWithRoleId == null || input.associatedWithRoleId === '' ? null : uuid(input.associatedWithRoleId, 'Associated role').toLowerCase();
  const roles = input.roleIdsCanEdit === undefined ? [] : input.roleIdsCanEdit;
  if (!Array.isArray(roles) || roles.length > 500) throw new HttpError(400, 'invalid_custom_field_roles', 'Select at most 500 roles.');
  result.roleIdsCanEdit = roles.map((id) => uuid(id, 'Role').toLowerCase());
  if (new Set(result.roleIdsCanEdit).size !== roles.length) throw new HttpError(400, 'invalid_custom_field_roles', 'Each role can be selected only once.');
  const options = input.options === undefined ? [] : input.options;
  if (!Array.isArray(options) || options.length > 500) throw new HttpError(400, 'invalid_custom_field_options', 'Add at most 500 dropdown options.');
  result.options = options.map((option) => {
    fieldsOnly(option, ['id', 'key', 'label']);
    const key = cleanText(option.key, 'Option key', 150, false);
    if (!/^[A-Za-z0-9_]+$/.test(key)) throw new HttpError(400, 'invalid_custom_field_options', 'Option keys can only contain letters, numbers, and underscores.');
    return { id: uuid(option.id, 'Option').toLowerCase(), key, label: cleanText(option.label, 'Option label', 200, false) };
  });
  if (new Set(result.options.map((option) => option.id)).size !== options.length || new Set(result.options.map((option) => option.key)).size !== options.length) {
    throw new HttpError(400, 'invalid_custom_field_options', 'Each dropdown option must have a distinct identifier and key.');
  }
  return result;
}
