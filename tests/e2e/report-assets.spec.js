test('source template settings bind headers and footers to a COA that retains its saved branding', async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const user = await createAccount(owner, { permissions: ['templates.read', 'templates.manage', 'samples.read', 'samples.create', 'samples.manage', 'test_requests.allocate', 'datasheets.execute', 'report_settings.manage'] });
  const session = await signIn({ identifier: user.username, password: user.password }); const account = { ...user, ...session };
  const work = (callback) => withSession(session.token, callback, { csrfToken: session.csrfToken });
  const flow = await prepareReportFlow(owner, account); const assets = await work(createReportAssets);
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await login(page, account); await page.goto(`/master_template_management/${flow.template.templateId}`);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  const settings = page.getByRole('dialog', { name: 'Settings', exact: true });
  await expect(settings.getByRole('combobox', { name: 'Non NABL Header', exact: true })).toBeEnabled();
  await expect(settings.getByRole('combobox', { name: 'Non NABL Header', exact: true })).toHaveValue('');
  await settings.getByRole('combobox', { name: 'Non NABL Header', exact: true }).selectOption(assets.header.id);
  await settings.getByRole('combobox', { name: 'Non-NABL Footer', exact: true }).selectOption(assets.footer.id);
  await expect(settings.getByRole('combobox', { name: 'NABL Header', exact: true })).toHaveValue('');
  await page.screenshot({ path: testInfo.outputPath('template-source-asset-settings.png'), fullPage: true, animations: 'disabled' });
  await settings.getByRole('button', { name: 'Save Settings', exact: true }).click();
  await expect(settings).not.toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expect(settings.getByRole('combobox', { name: 'Non NABL Header', exact: true })).toHaveValue(assets.header.id);
  await settings.getByRole('button', { name: 'Close', exact: true }).click();
  await page.goto(`/samples/${flow.sample.id}/coa`);
  await page.getByRole('button', { name: /^Consolidated/ }).click();
  await page.getByLabel('Consolidated Report template', { exact: true }).selectOption(flow.template.templateId);
  await page.getByRole('button', { name: 'Generate', exact: true }).click();
  const report = page.getByRole('article');
  await expect(report.getByText('FROZEN LABORATORY HEADER', { exact: true })).toBeVisible();
  await expect(report.getByText('FROZEN LABORATORY FOOTER', { exact: true })).toBeVisible();
  await expect(report.locator('img[alt="Synthetic logo"]')).toBeVisible();
  await work((client, identity) => saveReportDocument(client, identity, { ...assets.headerInput, revision: 1, requestId: randomUUID(), templateHtml: '<p>CHANGED LATER</p>' }));
  await page.reload();
  await expect(report.getByText('FROZEN LABORATORY HEADER', { exact: true })).toBeVisible();
  await expect(report.getByText('CHANGED LATER', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('coa-captured-assets-desktop.png'), fullPage: true, animations: 'disabled' });
  expect(errors).toEqual([]);
});
